const { chromium, devices } = require('playwright');
const BLOCK = [/facebook\.com\/tr/, /connect\.facebook\.net/, /google-analytics\.com/, /googletagmanager\.com/, /googleadservices\.com/, /doubleclick\.net/, /clarity\.ms/, /analytics\.tiktok\.com/, /monorail-edge\.shopifysvc\.com/, /\/\.well-known\/shopify\/monorail/, /\/api\/collect/, /bat\.bing\.com/, /trekkie/, /\/web-pixels/, /a\.klaviyo\.com\/client\/events/, /static-tracking\.klaviyo\.com/];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 1 });
  await ctx.route('**/*', r => BLOCK.some(re => re.test(r.request().url())) ? r.abort() : r.continue());
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => { if (!/Failed to fetch/.test(e.message)) errs.push(e.message.slice(0, 200)); });
  await p.goto('https://zeotein.com/products/zeotein-cacao-bag-30', { waitUntil: 'load' });
  await p.waitForTimeout(2500);
  const btn = p.locator('button.product-form__submit').first();
  await btn.scrollIntoViewIfNeeded();
  await btn.click();
  await p.waitForTimeout(3000);
  await p.screenshot({ path: 'vp/cart-1-after-add.png' });
  const cart = await p.evaluate(async () => (await fetch('/cart.js')).json());
  console.log('cart items', cart.items.map(i => ({ t: i.product_title, v: i.variant_title, q: i.quantity, price: i.final_line_price / 100, plan: i.selling_plan_allocation && i.selling_plan_allocation.selling_plan.name })), 'total', cart.total_price / 100);
  await p.goto('https://zeotein.com/cart', { waitUntil: 'load' });
  await p.waitForTimeout(3000);
  await p.screenshot({ path: 'vp/cart-2-page.png', fullPage: true });
  const h = await p.evaluate(() => document.body.scrollHeight); console.log('cart page height', h);
  const co = p.locator('#checkout, button[name="checkout"]').first();
  console.log('checkout button count', await p.locator('#checkout, button[name="checkout"]').count());
  await co.click();
  await p.waitForTimeout(8000);
  console.log('after checkout url', p.url().replace(/\?.*/, '?…'));
  await p.screenshot({ path: 'vp/cart-3-checkout.png', fullPage: true });
  console.log('errors', errs);
  await b.close();
})();
